import { StateSchema, MessagesValue, type GraphNode, StateGraph, START, END } from "@langchain/langgraph";
import z from "zod"
import { mistralModel, cohoreModel, googlemodel,chatgroq } from "./model.ai.js"
import { HumanMessage, createAgent, providerStrategy, toolStrategy } from "langchain";

const state = new StateSchema({
    problem: z.string().default(""),
    solution_1: z.string().default(""),
    solution_2: z.string().default(""),

    judge: z.object({
        solution_1: z.number().default(0),
        solution_2: z.number().default(0),
        solution_1_reasoning: z.string().default(""),
        solution_2_reasoning: z.string().default(""),
    })
})


const solutionNode: GraphNode<typeof state> = async (state) => {

    const [mistralResponse, cohoreResponse] = await Promise.all([
        chatgroq.invoke(state.problem),
        cohoreModel.invoke(state.problem),

    ])
    return {
        solution_1: mistralResponse.text,
        solution_2: cohoreResponse.text,
    }
}

const judgeNode: GraphNode<typeof state> = async (state) => {

    const { problem, solution_1, solution_2 } = state;

    const judge = createAgent({
        model: googlemodel,
        responseFormat: providerStrategy(z.object({
            solution_1_score: z.number().min(0).max(10),
            solution_2_score: z.number().min(0).max(10),
            solution_1_reasoning: z.string(),
            solution_2_reasoning: z.string(),
        })),

        systemPrompt: ` you are a judge tasked with evaluating two solutions to agenerated by diffrent AI models . Please provide a score between 0 and 10 for each solution, along with a brief reasoning for your scores.`
    })

    const judgeResponse = await judge.invoke({
        messages: [
            new HumanMessage(`
                Problem: ${problem}
                Solution 1: ${solution_1}
                Solution 2: ${solution_2}
                
                please evaluate the solutions and provide score and reasoning in the following format:`)
        ]
    })

    const { solution_1_score, solution_2_score, solution_1_reasoning, solution_2_reasoning } = judgeResponse.structuredResponse

    return {
        judge:{
            solution_1: solution_1_score,
            solution_2: solution_2_score,
            solution_1_reasoning: solution_1_reasoning,
            solution_2_reasoning: solution_2_reasoning
        }
    }
}

const graph = new StateGraph(state)
.addNode("solution", solutionNode)
.addNode("judge_node", judgeNode)
.addEdge(START,"solution")
.addEdge("solution","judge_node")
.addEdge("judge_node",END)
.compile()

export default async function rungraph(problem: string){
    const result = await graph.invoke({
        problem:problem
    })

    return result
}
